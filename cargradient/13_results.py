#!/usr/bin/env python3
"""
13_results.py -- ROOT/RESULTS.md from ROOT/out/, failures first.

Every number is printed through cglib.printed(), so 14_manifest.py --check
can find each one. Nothing here computes a tested number.
"""
import os

import cglib as L

NAMES = {"T1": "T1, their sign on HDB flats, 2002Q2 to 2015Q4 (less 2012Q1)",
         "T2": "T2, the same, 2016Q1 to 2026Q3 (less 2020Q2)",
         "T3": "T3, weaker after February 2018 (2018Q2 to 2026Q3 against 2012Q2 to 2017Q3)"}
ORDER = {"FAIL": 0, "NOT": 1, "SURVIVE": 2}


def p(T, k):
    return L.printed(k, T[k]) if k in T else "n/a"


def test_lines(t, T):
    oc = T[f"{t}_outcome"]
    out = [f"### {NAMES[t]}: {oc}", ""]
    if t in ("T1", "T2"):
        out += [f"- Estimate (COE premium x km): {p(T, t + '_est')}, standard error {p(T, t + '_se')}, "
                f"95 per cent interval {p(T, t + '_lo')} to {p(T, t + '_hi')}.",
                f"- Sales {p(T, t + '_n')}, blocks {p(T, t + '_blocks')}, quarters {p(T, t + '_quarters')}.",
                f"- Gate 1, geocoded share of the window's sales: {p(T, t + '_geo_share')} (line 95.00%).",
                f"- Gate 2, first-stage F: {p(T, t + '_F')} (line 10.0)."]
    else:
        out += [f"- Before-window estimate: {p(T, 'T3_before_est')}, standard error {p(T, 'T3_before_se')}, "
                f"interval {p(T, 'T3_before_lo')} to {p(T, 'T3_before_hi')}. After-window estimate "
                f"(before plus difference): {p(T, 'T3_after_est')}.",
                f"- Difference, after minus before: {p(T, 'T3_diff_est')}, standard error "
                f"{p(T, 'T3_diff_se')}, interval {p(T, 'T3_diff_lo')} to {p(T, 'T3_diff_hi')}.",
                f"- Sales {p(T, 'T3_n')}, blocks {p(T, 'T3_blocks')}.",
                f"- Gate 1: {p(T, 'T3_geo_share_before')} before, {p(T, 'T3_geo_share_after')} after "
                f"(line 95.00%).",
                f"- Gate 2, first-stage F: {p(T, 'T3_F_before')} before, {p(T, 'T3_F_after')} after "
                f"(line 10.0)."]
    return out + [""]


def main():
    a = L.args("cargradient RESULTS.md.")
    P = L.paths(a.root)
    T = {r["key"]: r["value"] for r in L.read_csv(os.path.join(P["out"], "tests.csv"))}
    calc = {r["key"]: r["value"] for r in L.read_csv(os.path.join(P["out"], "calc_7a.csv"))}
    sens = L.read_csv(os.path.join(P["out"], "sensitivities.csv"))
    verdict = open(os.path.join(P["out"], "verdict.txt"), encoding="utf-8").read().strip()
    rep = os.path.join(P["out"], "reproduce.txt")
    lines = ["# RESULTS -- cargradient", "",
             "Generated by 13_results.py from out/. Failures first. Every number below is checked "
             "against out/ by 14_manifest.py --check.", "",
             "## Verdict (THESIS section 8)", "", verdict, "",
             "At most, this explains part of the near-town premium, not million-dollar flats as a whole.", "",
             "## Tests, failures first", ""]
    tests = sorted(L.SCORED, key=lambda t: (ORDER[T[f"{t}_outcome"].split("_")[0]], t))
    for t in tests:
        lines += test_lines(t, T)
    lines += ["## Scorecard", "",
              f"- Scored: {p(T, 'n_scored')}; held: {p(T, 'held_count')}."]
    if "brier" in T:
        lines += [f"- Brier score: {p(T, 'brier')}; expected held: {p(T, 'expected_held')}."]
    else:
        lines += ["- Brier score: not computed (confidences are set at the seal)."]
    lines += ["", "## Reported calculation (section 7A, not scored)", "",
              f"- COE premium, mean of the quarters with bidding: {p(calc, 'coebar_2020')} in 2020, "
              f"{p(calc, 'coebar_2023')} in 2023, a change of {p(calc, 'dcoe')}.",
              f"- Bootstrap draws set: {p(calc, 'boot_n')} (run only when the share is readable)."]
    if calc["share_readable"] == "True":
        lines += [f"- That COE change implies a change of {p(calc, 'dgap_implied')} dollars per square metre in the gap between a "
                  f"flat 5 km and one 20 km from Raffles Place (interval {p(calc, 'dgap_implied_lo')} to "
                  f"{p(calc, 'dgap_implied_hi')}).",
                  f"- The gap actually changed by {p(calc, 'dgap_actual')} (interval {p(calc, 'dgap_actual_lo')} "
                  f"to {p(calc, 'dgap_actual_hi')}).",
                  f"- Share: about {p(calc, 'share')} (bootstrap interval {p(calc, 'share_lo')} to "
                  f"{p(calc, 'share_hi')})."]
    else:
        lines += [f"- Implied change in the gap: {p(calc, 'dgap_implied')} dollars per square metre (interval "
                  f"{p(calc, 'dgap_implied_lo')} to {p(calc, 'dgap_implied_hi')}).",
                  f"- Actual change: {p(calc, 'dgap_actual')} (interval {p(calc, 'dgap_actual_lo')} to "
                  f"{p(calc, 'dgap_actual_hi')}). The share is not meaningful: the gap did not clearly "
                  "change, or moved the other way (THESIS section 7A)."]
    lines += ["", "## Sensitivities (section 7, reported, not scored)", "",
              "| Name | Test | Estimate | Interval | Sales | Would read as |", "|---|---|---|---|---|---|"]
    for r in sens:
        lines.append(f"| {r['name']} | {r['test']} | {L.printed('x_est', r['est'])} | "
                     f"{L.printed('x_lo', r['lo'])} to {L.printed('x_hi', r['hi'])} | {r['n']} | "
                     f"{r['outcome_if_scored']}{' (' + r['note'] + ')' if r['note'] else ''} |")
    lines += ["", "## Independent reproduction (15_reproduce.py)", ""]
    lines += [open(rep).read().strip() if os.path.exists(rep) else "Not run yet."]
    L.write_text(P["results"], "\n".join(lines) + "\n")
    print("wrote", P["results"])


if __name__ == "__main__":
    main()
